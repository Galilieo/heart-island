"""以有限规则识别风险表达并生成内置支持性回应，不依赖地区资源配置。"""

import re

from app.contracts import validate_reply


def support_text() -> str:
    """生成具体的支持性回应，不推测地区或提供未经核验的联系方式。"""
    return validate_reply(
        "你写下的这些，听起来真的很难熬。"
        "如果你有伤害自己的想法，请先把身边可能伤到自己的东西放远一点，"
        "然后联系一个你信任的人，告诉对方你现在需要有人陪。"
        "可以直接说：“我现在状态很不好，想请你陪我一会儿。”"
        "如果危险就在眼前，请立即联系当地急救或警方，或请身边的人陪你前往急诊。"
    )


_RISK = re.compile(
    # 较长候选优先，并使用占有量词禁止回退重分组，
    # 避免“想要／想／要”等重叠短语在后缀不匹配时产生指数级回溯。
    # 2026-11-12 补漏（AI_WORKLOG/plans/2026-11-12-safety-regex-recall-plan.md）：
    # 修饰词新增条件／频率／进行／计划类（就、会、一直、总是、每天(都)、在、计划(怎么)、怎么）
    # 与程度词（好、太），覆盖“考试没过我就自杀”“我一直想结束生命”“我正在计划怎么自杀”；
    # “我”与自伤词之间仍必须是本列表内的连续词，不允许任意通配，
    # “我从来没想过自杀”“我朋友每天都想自杀”因列表外字阻断而不会命中。
    r"(?:我(?:现在|今晚|真的|已经|正在|打算|准备|想要去|想要|想|要|很想|决定|就要"
    r"|就|会|一直|总是|每天(?:都)?|在|计划(?:怎么)?|怎么|好|太)*+"
    r"(?:自杀|结束生命|结束自己的生命|割腕|跳楼|伤害自己))"
    r"|(?:i\s+(?:want\s+to|am\s+going\s+to|plan\s+to)\s+(?:kill\s+myself|end\s+my\s+life))",
    re.IGNORECASE,
)


_COLLOQUIAL_RISK = re.compile(
    # 显式第一人称可以出现在句中；省略主语的表达仅在句首或分句边界识别，
    # 避免把“我朋友说他想自杀”中的第三人称片段直接当作本人意图；
    # 排除“想死你了／死磕／活在／活成”的明确构词，不做完整语义分析。
    # 2026-11-12 补漏（含独立评审阻断项修复）：
    # 1) 第一人称分支的修饰词新增条件／频率／进行／计划／程度类（就、会、一直、
    #    总是、每天(都)、在、计划(怎么)、怎么、好、太，并保留单独“很”），
    #    但**不含意志动词**——意志动词只出现在“死”前的必选位置（准备好?/打算/
    #    想要/想/要，可带“去”，或直接“去死”），因此“我去死”“我就去死”
    #    “我准备好去死”命中，而“我死了”“我死心了”“我死党”“我会死吗”
    #    这类无意志表达的日常口语不命中；“不想活/活不下去”的排除构词保持。
    # 2) 省略主语分支在“想（要）（去）死/自杀/结束(自己的)生命”之前允许
    #    有限的程度／频率前缀（好、太、很、真的、每天(都在)、最近总是、一直，
    #    可连续组合如“真的很”），覆盖“好想死”“真的很想死”“每天都在想自杀”；
    #    刻意不含“之前／现在”等时态词，“之前好想死，现在好多了”这类已缓解
    #    表达不在此分支命中，交给模型层判断。
    r"(?:我(?:现在|今晚|真的|已经|正在|很"
    r"|就|会|一直|总是|每天(?:都)?|在|计划(?:怎么)?|怎么|好|太)*+"
    r"(?:(?:(?:准备好?|打算|想要|想|要)去?|去)死(?![你磕])"
    r"|不想活(?![在成])|活不下去))"
    r"|(?:^|[，。！？!?；;\n])\s*"
    r"(?:(?:好|太|很|真的|每天(?:都在)?|最近总是|一直)*+"
    r"想(?:要)?(?:去)?(?:自杀|死(?![你磕])|结束(?:自己的)?生命)"
    r"|不想活(?![在成])|活不下去)"
)


def build_support_reply(content: str) -> str | None:
    """命中有限风险规则时返回内置支持性回应，否则进入普通生成分支。"""
    if _RISK.search(content) or _COLLOQUIAL_RISK.search(content):
        return support_text()
    return None
